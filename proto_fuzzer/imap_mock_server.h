/// @file
/// @brief Command-aware in-process peer for curl's IMAP state machine.

#ifndef PROTO_FUZZER_IMAP_MOCK_SERVER_H_
#define PROTO_FUZZER_IMAP_MOCK_SERVER_H_

#include <cstddef>
#include <string>
#include <string_view>

#include "proto_fuzzer/pingpong_mock_server.h"

namespace proto_fuzzer {

/// @class proto_fuzzer::ImapMockServer
/// @brief Services curl's single-connection, tagged IMAP exchange.
///
/// IMAP needs neither a data channel nor a second script per socket. Curl sends
/// one tagged command at a time and waits for the matching tagged completion,
/// so this peer treats Scenario.connection as a command-aligned reply script.
/// `initial_response` is the `* OK` greeting; each `on_readable` entry is the
/// reply to the next command (CAPABILITY, LOGIN/AUTHENTICATE, SELECT, FETCH,
/// APPEND, SEARCH, or LIST).
///
/// Unlike FTP and POP3, IMAP command tags are generated by curl from a
/// process-global connection id, so a seed cannot contain them. A scripted line
/// that begins with `OK`, `NO`, `BAD`, or `PREAUTH` therefore has the tag of the
/// command currently being answered prepended. Untagged (`*`) and continuation
/// (`+`) lines are sent unchanged. A `{N}` literal at the end of a line is
/// copied with the next N bytes untouched, so FETCH bodies and a tagged
/// completion can share one scripted chunk.
///
/// APPEND is the only command whose reply is not written in full up front.
/// After the peer accepts a `+` continuation it drains exactly the literal size
/// announced by the command and pre-queues the next scripted reply as the final
/// tagged completion, mirroring curl's blocking imap_done() wait.
class ImapMockServer final : public PingpongMockServer {
 public:
  ImapMockServer();

  ~ImapMockServer() override;

  ImapMockServer(const ImapMockServer&) = delete;
  ImapMockServer& operator=(const ImapMockServer&) = delete;

 protected:
  void HandleLine(std::string_view line) override;

  void ResetProtocolState() override;

  void QueueShutdownReply() override;

 private:
  /// Liveness reply for curl's blocking LOGOUT during teardown. IMAP requires a
  /// tagged line, so the peer predicts the next command id from the last tag it
  /// observed.
  static constexpr std::string_view kShutdownTail = " OK LOGOUT completed\r\n";

  // Resolve a scripted reply into wire bytes.
  std::string RewriteReply(std::string_view response) const;

  // Whether a complete line needs the current command tag prepended.
  static bool StatusLineNeedsTag(std::string_view line);

  // Literal byte count for a trailing `{N}` marker, or 0 when absent.
  static std::size_t LiteralSize(std::string_view line);

  // Literal size announced by an APPEND command, or max size_t when absent.
  static std::size_t AppendLiteralSize(std::string_view command);

  // Tag curl will use for the next command, derived from the current tag.
  std::string NextCommandTag() const;

  /// Tag of the command currently being answered.
  std::string current_tag_;
};

}  // namespace proto_fuzzer

#endif  // PROTO_FUZZER_IMAP_MOCK_SERVER_H_
